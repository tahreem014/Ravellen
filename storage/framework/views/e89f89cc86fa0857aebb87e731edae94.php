<p>We understand that ceramic and fragile products require extra care during shipping.</p>
<p>If your ceramic item arrives damaged, please contact us within 24 hours of delivery and provide the required unboxing video.</p>
<p>Each case will be reviewed individually.</p>
<p>Depending on the nature of the damage, availability of the item, and circumstances of the delivery, Ravellen may offer a replacement, refund, or another appropriate resolution.</p>

<h2>7. Change of Mind &amp; Exchanges</h2>

<h3>Change of Mind</h3>
<p>We do not accept returns simply because a customer has changed their mind, no longer wants the product, or is dissatisfied with the surprise contents of a mystery item.</p>
<p>Please carefully review your order before completing your purchase.</p>

<h3>Exchanges</h3>
<p>Ravellen does not offer exchanges for purchased items.</p>
<p>Exceptions may be considered when an item is damaged or incorrect due to an issue caused by Ravellen or the courier.</p>

<h2>8. Order Cancellation &amp; Changes</h2>

<h3>Order Cancellation</h3>
<p>Customers may request an order cancellation <strong>before the order has been dispatched</strong>.</p>
<p>Cancellation requests must be submitted as early as possible.</p>
<p>Once an order has been dispatched, cancellation requests will no longer be accepted.</p>
<p>For pre-orders, please contact us directly regarding cancellation requests before the order is dispatched.</p>

<h3>Order Changes</h3>
<p>If you need to make changes to your order, such as correcting your delivery address or modifying an item, please contact us as soon as possible.</p>
<p>We will do our best to accommodate your request, but changes cannot be guaranteed once your order has entered the packing or dispatch process.</p>

