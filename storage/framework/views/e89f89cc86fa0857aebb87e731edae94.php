</div>
<p>All orders must be paid for in advance.</p>

<h3>Complete Orders</h3>
<p>For products that are currently available in stock, <strong>full payment is required before the order is confirmed and dispatched.</strong></p>

<h3>Pre-orders</h3>
<p>Pre-orders require a <strong>40% advance payment</strong> to secure your slot in the first available stock.</p>
<p>Once the products have been restocked:</p>
