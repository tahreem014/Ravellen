<p>Return shipping charges depend on the reason for the return.</p>

<h3>Ravellen Covers Return Shipping When:</h3>
<ul>
    <li>The item was damaged during delivery by the courier.</li>
    <li>The customer received an incorrect item due to an error on our part.</li>
    <li>The return is approved because of an issue that is our responsibility.</li>
</ul>

<h3>Customer Covers Return Shipping When:</h3>
<ul>
    <li>The customer refuses to accept the parcel upon delivery.</li>
    <li>The customer does not receive or collect the parcel.</li>
    <li>The parcel is returned because of the customer's own actions or circumstances.</li>
</ul>
<p>In these situations, the customer is responsible for the applicable return shipping charges.</p>
<p>Please ensure that your delivery information is accurate and that you are available to receive your parcel.</p>

