    <li>Refunds are not offered for preference-based dissatisfaction with mystery contents.</li>
    <li>Customers cannot request a specific mystery item unless customisation is explicitly offered.</li>
    <li>Damaged, incorrect, or missing items may still qualify for review under our damaged-item policy.</li>
