<p>A 40% advance payment is required to secure a place in the first available stock.</p>
<p>The remaining payment must be completed once the products arrive and the customer has been notified.</p>
<p>Orders will only be fully confirmed for dispatch after the remaining payment has been received.</p>
<p>We appreciate your patience while waiting for your little surprises to arrive!</p>

<h2>4. Returns &amp; Refunds</h2>
<p>We want you to love your Ravellen purchases! However, because some of our products are mystery-based and carefully prepared, we have a few important return guidelines.</p>

<h3>Return Eligibility</h3>
<p>Returns may be accepted for eligible items that are:</p>
<ul>
    <li>Unused and in their original condition.</li>
    <li>Returned with their original packaging, where applicable.</li>
    <li>Reported to us within <strong>3 days of delivery</strong>.</li>
    <li>Approved by Ravellen before being returned.</li>
</ul>
<p>Customers must contact us before sending any item back.</p>

<h3>Damaged, Incorrect, or Missing Items</h3>
<p>If you receive an item that is damaged, incorrect, or missing from your order, please contact us within 24 hours of delivery.</p>
<p>To help us investigate and resolve the issue, an <strong>unboxing video is required</strong>.</p>
<p>The video should clearly show the package being opened and the condition of the items received.</p>
<p>Please retain the original packaging until the issue has been resolved.</p>
<p>If the issue is confirmed to be our responsibility or caused by the courier during delivery, Ravellen will cover the applicable return shipping charges.</p>
<p>Depending on the situation and product availability, we may offer a replacement or refund.</p>

<h3>Refunds</h3>
<p>Refunds may be offered for eligible damaged, incorrect, or missing items after the issue has been reviewed and approved.</p>
<p>Depending on the circumstances, Ravellen may offer:</p>
<ul>
    <li>A replacement, if the item is available.</li>
    <li>A refund through an appropriate payment method.</li>
    <li>Another suitable resolution agreed upon with the customer.</li>
</ul>
<p>Refunds are not automatically guaranteed for every return request. Each case will be reviewed individually.</p>

